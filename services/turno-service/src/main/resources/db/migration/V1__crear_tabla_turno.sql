-- paciente_id, medico_id y especialidad_id son referencias LÓGICAS a otros microservicios:
-- no hay claves foráneas porque esos datos viven en otras bases de datos.
CREATE TABLE turno (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id      BIGINT       NOT NULL,
    medico_id        BIGINT       NOT NULL,
    especialidad_id  BIGINT       NOT NULL,
    fecha_hora       TIMESTAMP    NOT NULL,
    fecha_hora_fin   TIMESTAMP    NOT NULL,
    duracion_minutos INTEGER      NOT NULL,
    estado           VARCHAR(20)  NOT NULL,
    motivo           VARCHAR(255),
    creado_en        TIMESTAMP    NOT NULL,
    version          BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_turno_estado CHECK (estado IN ('PROGRAMADO', 'CANCELADO', 'ATENDIDO')),
    CONSTRAINT ck_turno_duracion CHECK (duracion_minutos BETWEEN 10 AND 120),
    CONSTRAINT ck_turno_intervalo CHECK (fecha_hora_fin > fecha_hora)
);

CREATE INDEX idx_turno_medico_fecha ON turno (medico_id, fecha_hora);
CREATE INDEX idx_turno_paciente_fecha ON turno (paciente_id, fecha_hora);
CREATE INDEX idx_turno_fecha ON turno (fecha_hora);
