-- Cuentas para iniciar sesión. La contraseña NUNCA se guarda: solo su hash BCrypt.
-- paciente_id vincula la cuenta de un paciente con su ficha. Es una FK LOCAL (misma base de datos).
CREATE TABLE usuario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario     VARCHAR(60)  NOT NULL,
    clave_hash  VARCHAR(100) NOT NULL,
    nombre      VARCHAR(120) NOT NULL,
    rol         VARCHAR(20)  NOT NULL,
    paciente_id BIGINT,
    activo      BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en   TIMESTAMP    NOT NULL,
    CONSTRAINT uk_usuario_usuario UNIQUE (usuario),
    CONSTRAINT uk_usuario_paciente UNIQUE (paciente_id),
    CONSTRAINT fk_usuario_paciente FOREIGN KEY (paciente_id) REFERENCES paciente (id),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('ADMINISTRATIVO', 'MEDICO', 'PACIENTE')),
    CONSTRAINT ck_usuario_paciente CHECK ((rol = 'PACIENTE') = (paciente_id IS NOT NULL))
);
