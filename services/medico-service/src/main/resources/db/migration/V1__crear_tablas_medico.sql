CREATE TABLE medico (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(80)  NOT NULL,
    apellido  VARCHAR(80)  NOT NULL,
    matricula VARCHAR(30)  NOT NULL,
    email     VARCHAR(120),
    telefono  VARCHAR(30),
    activo    BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_medico_matricula UNIQUE (matricula)
);

-- Relación médico-especialidad. medico_id es FK LOCAL (misma base).
-- especialidad_id es una referencia LÓGICA al microservicio Especialidad: no hay FK entre bases,
-- la validez se comprueba llamando a su API REST al crear/editar el médico.
CREATE TABLE medico_especialidad (
    medico_id       BIGINT NOT NULL,
    especialidad_id BIGINT NOT NULL,
    PRIMARY KEY (medico_id, especialidad_id),
    CONSTRAINT fk_medico_especialidad_medico FOREIGN KEY (medico_id) REFERENCES medico (id)
);

CREATE INDEX idx_medico_especialidad_especialidad ON medico_especialidad (especialidad_id);
