-- turno_id, paciente_id, medico_id y especialidad_id son referencias LÓGICAS a otros microservicios
-- (no hay claves foráneas entre bases de datos distintas).
CREATE TABLE consulta (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turno_id        BIGINT        NOT NULL,
    paciente_id     BIGINT        NOT NULL,
    medico_id       BIGINT        NOT NULL,
    especialidad_id BIGINT        NOT NULL,
    fecha_turno     TIMESTAMP     NOT NULL,
    registrada_en   TIMESTAMP     NOT NULL,
    motivo          VARCHAR(500)  NOT NULL,
    diagnostico     VARCHAR(2000),
    tratamiento     VARCHAR(2000),
    observaciones   VARCHAR(2000),
    version         BIGINT        NOT NULL DEFAULT 0,
    -- Un turno tiene como máximo una consulta
    CONSTRAINT uk_consulta_turno UNIQUE (turno_id)
);

CREATE INDEX idx_consulta_paciente ON consulta (paciente_id);
CREATE INDEX idx_consulta_medico ON consulta (medico_id);
